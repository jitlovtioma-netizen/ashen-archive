// Одноразовый скрипт: создание героя Каэль Валькрейн (PF2E) и привязка
// персонажей к аккаунтам по списку пользователя (Task: привязка профилей).
// Запуск: bun run prisma/bind-characters.ts
// ВНИМАНИЕ: это НЕ re-seed — прогресс пользователей не затрагивается.

import { db } from '../src/lib/db'

const KAEL_DESCRIPTION = `▓▒░ Каэль Валькрейн ░▒▓ — ведьмак и охотник на демонов. Рождён в суровую зиму 4697 года, 15 декабря, в день великой метели, в крепости Болигар — у самой западной границы Менделва, где война с Бездной не утихала ни на день. Хилый недоношенный мальчишка, которому сама судьба, казалось, пророчила смерть, — выжил. В одиннадцать лет он пережил кровавое падение крепости: девятнадцать часов ада, после которых от прежней жизни остался лишь пепел и клятва мстить. Дорога привела его в Кенабрес, где к девятнадцати годам он стал капитаном одиннадцатого гарнизона — овладел дьявольским языком так, что демоны порой принимали его за своего, изучил ведьмачьи знаки, тауматургию боли и смертоносные техники разных народов.\n\nКогда король Сатра предал Мендев и заключил пакт с Бездной, Каэль поднял гарнизоны в крестовый поход. Семь дней штурма столицы обернулись резнёй — выживших можно пересчитать по пальцам одной руки. С тех пор ведьмак винит себя за каждую потерянную жизнь; годы скитаний по Нимерии и речным королевствам выжгли в нём паранойю и глухую тоску, а совесть жжёт сильнее любого клейма.\n\nПерелом произошёл в заснеженных горах Селлен Хилс, где он нашёл гнездо с умирающим дракончиком и, невзирая на риск, выходил его. Малыша он назвал Лэфтарионом — в честь героя древних легенд о серебряной драконице Теренделев. С этим маленьким светом на плече Каэль уверовал в Апсу, бога свободы и драконов, и впервые за долгие годы стал искать не месть, а новую жизнь: подарить Мендеву свободу и низвергнуть короля-предателя. В пути его странным напарником стал демон-изгой Эдмунт Ван Рейх — «Ты мой клинок, а я твой свет», — сказал ему однажды Лэфтарион, и эти слова ведьмак носит теперь как второй обет.\n\nНыне дорога ведьмака и его дракона привела в молодую деревню под правлением Линдемира Суртова.`

async function main() {
  // ── 1. Герой Каэль Валькрейн (PF2E) ──────────────────────────────
  let kael = await db.character.findFirst({
    where: { name: 'Каэль Валькрейн', system: 'PF2E' },
  })
  if (!kael) {
    kael = await db.character.create({
      data: {
        name: 'Каэль Валькрейн',
        title: 'Ведьмак · Охотник на Демонов',
        system: 'PF2E',
        category: 'Ведьмак',
        race: 'Человек',
        description: KAEL_DESCRIPTION,
        sigil: '🗡',
        mapX: 100,
        mapY: 400,
        imageUrl: '/heroes/kael.png',
        kind: 'HERO',
        status: 'ALIVE',
      },
    })
    console.log(`✓ СОЗДАН герой: ${kael.name} (${kael.id})`)
  } else {
    console.log(`= герой уже существует: ${kael.name} (${kael.id})`)
  }

  // ── 2. Привязки «логин → персонаж» по списку пользователя ───────
  const bindings: Record<string, string> = {
    sashakarev1809: 'Бруно',
    IlyaKazakhStrong: 'Мартин МакДона',
    NiT: 'Мартин Осборн',
    ps1x0k1d: 'Реми',
    GTT_EDMI: 'Каэль Валькрейн',
    xlov21: 'Линдэмир Суртов',
    EvaMoon: 'Диана',
    Mira: 'Мира',
  }

  for (const [login, charName] of Object.entries(bindings)) {
    const user = await db.user.findUnique({ where: { login } })
    if (!user) {
      console.log(`✗ ${login}: пользователь не найден`)
      continue
    }
    const char = await db.character.findFirst({
      where: { name: charName, system: user.system },
    })
    if (!char) {
      console.log(`✗ ${login}: персонаж «${charName}» не найден`)
      continue
    }
    await db.user.update({
      where: { login },
      data: { characterId: char.id },
    })
    console.log(`✓ ПРИВЯЗАН ${login} → ${char.name} [${user.system}]`)
  }

  // ── 3. Итоговая сводка ───────────────────────────────────────────
  const users = await db.user.findMany({
    orderBy: { createdAt: 'asc' },
    select: { login: true, system: true, role: true, characterId: true },
  })
  console.log('\n── ИТОГО ──')
  for (const u of users) {
    const c = u.characterId
      ? await db.character.findUnique({ where: { id: u.characterId } })
      : null
    console.log(
      `${u.login.padEnd(18)} ${u.system.padEnd(5)} ${u.role.padEnd(6)} → ${c?.name ?? '—'}`,
    )
  }
}

main()
  .then(() => process.exit(0))
  .catch((e) => {
    console.error(e)
    process.exit(1)
  })
