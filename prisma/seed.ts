// Превращает текст в «расплавленное» нечитаемое месиво без смысла.
// Заливает каждый символ 4-6 комбинирующими диакритиками (zalgo) и вставляет
// блочные символы (▓▒░█▚▞). Используется для описаний всех секретов,
