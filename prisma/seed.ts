// Если NEXT_PUBLIC_SUPABASE_URL не задан (локальный dev без Supabase) —
// возвращаем локальный путь /heroes/... /gods/... как fallback.
const SUPA_URL = process.env.NEXT_PUBLIC_SUPABASE_URL
function img(path: string): string {
  if (SUPA_URL) {
    return `${SUPA_URL}/storage/v1/object/public/images/${path}`
  }
  // Fallback для локального dev: картинки лежат в /public
  return `/${path}`
}

