// ─── ZALGO-расплавитель текста ───────────────────────────────────────────────
// Превращает текст в «расплавленное» нечитаемое месиво: каждый символ
// заливается N комбинирующими диакритиками + вставляются блочные символы.
// Используется для искажённых (isCorrupted) записей в UI.

const ZALGO_MARKS = [
  "\u030d", "\u030e", "\u0304", "\u0305", "\u0310", "\u0312", "\u0336", "\u0337",
  "\u0338", "\u033b", "\u033c", "\u033d", "\u033e", "\u0340", "\u0341", "\u0342",
  "\u0343", "\u0344", "\u0345", "\u0346", "\u0347", "\u0348", "\u0349", "\u034a",
  "\u034b", "\u034c", "\u034d", "\u034e", "\u0350", "\u0351", "\u0352", "\u0353",
  "\u0354", "\u0355", "\u0356", "\u0357", "\u0358", "\u0359", "\u035a", "\u035b",
  "\u035c", "\u035d", "\u035e", "\u035f", "\u0360", "\u0361", "\u0362", "\u0363",
  "\u0364", "\u0365", "\u0366", "\u0367", "\u0368", "\u0369", "\u036a", "\u036b",
  "\u036c", "\u036d", "\u036e", "\u036f",
  "\u031a", "\u031b", "\u031c", "\u031d", "\u031e", "\u031f", "\u0320", "\u0321",
  "\u0322", "\u0323", "\u0324", "\u0325", "\u0326", "\u0327", "\u0328", "\u0329",
  "\u032a", "\u032b", "\u032c", "\u032d", "\u032e", "\u032f", "\u0330", "\u0331",
  "\u0332", "\u0333", "\u0334", "\u0335",
];

const BLOCKS = "▓▒░█▚▞▐▌";

/**
 * Расплавить текст — залить каждый символ zalgo-метками и блочными символами.
 * @param text исходный текст
 * @param intensity количество меток на символ (по умолчанию 4-6)
 */
export function meltText(text: string, intensity: number = 5): string {
  const n = Math.max(1, intensity);
  return text
    .split("")
    .map((ch) => {
      if (ch === " " || ch === "\n" || ch === "\t") return ch;
      let z = "";
      for (let i = 0; i < n; i++) {
        z += ZALGO_MARKS[Math.floor(Math.random() * ZALGO_MARKS.length)];
      }
      const prefix =
        Math.random() < 0.35 ? BLOCKS[Math.floor(Math.random() * BLOCKS.length)] : "";
      return prefix + ch + z;
    })
    .join("");
}
