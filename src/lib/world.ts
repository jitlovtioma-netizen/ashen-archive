// ─────────────────────────────────────────────────────────────────────────────
// МИРЫ И ИХ ПОДАЧА
//   pf2e — Голарион: компьютерный CRT-архив (как было).
//   dnd  — Элария: «Хроника Созидателя» — тот же архив, но рассказанный
//          его автором: пергамент, фиолет, золото, перо и свечи.
// Тема включается атрибутом <html data-world="…"> (см. page.tsx), вся
// перекраска — в globals.css, блок «ХРОНИКА ЭЛАРИИ».
// ─────────────────────────────────────────────────────────────────────────────

export type World = "dnd" | "pf2e";

export function worldOf(system: GameSystem | null | undefined): World {
  return system === "DND" ? "dnd" : "pf2e";
}

/** Текущий мир по вошедшему стражу (до входа — CRT). */
export function useWorld(): World | null {
  const system = useArchive((s) => s.user?.system);
  return system ? worldOf(system) : null;
}

